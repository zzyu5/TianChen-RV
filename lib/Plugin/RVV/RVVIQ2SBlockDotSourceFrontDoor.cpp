//===- RVVIQ2SBlockDotSourceFrontDoor.cpp ------------------------------===//
//
// Track B auto-lowering, the SUPER-BLOCK GRID-CODEBOOK rung -- the FINAL literal
// block-dot zoo bucket (the deep IQ tail's super-block grid codebook). The COMPILER
// auto-constructs the complete tcrv.exec.kernel + variant + dispatch/fallback
// scaffold around ONE attr-less tcrv_rvv.iq2_s_q8_k_block_dot op, from a marked
// GENERIC source carrying the ggml `ggml_vec_dot_iq2_s_q8_K` OPERATOR IDENTITY,
// instead of a per-kernel hand-authored super-block grid-codebook block-dot emitter
// input.
//
// WHAT THIS RUNG COMBINES: iq2_s is the THIRD member of the deep IQ tail and the
// SIBLING of iq2_xxs / iq2_xs. It wraps a 1024-entry packed uint64 GRID codebook
// (each entry encodes 8 int8 grid values, indexed by a 10-bit index) in the q6_K-style
// super-block structure (QK_K==256, 8 sub-blocks of 32, the q8_K activation with its
// leading fp32 scale). Three structural deltas vs iq2_xs make it the deep-tail member:
// (a) a 1024-entry grid; (b) the 10-bit index is assembled from a single qs index byte
// plus 2 qh-plane bits (idx = qs[l] | ((qh[ib32] << (8-2*l)) & 0x300)); (c) the per-lane
// SIGN is read DIRECTLY from an EXPLICIT sign-byte region INSIDE qs[64] at qs+QK_K/8 =
// qs+32 (NO ksigns lookup). The EXPLICIT per-sub-block 4-bit scales (ls = 2*(sc&0xf)+1)
// fold in the INTEGER domain with a trailing 0.125f factor. All of this is first-class
// STRUCTURE inside the op + its existing iq2_s emitter. So the front door does NOT
// hand-roll any of it; it supplies (a) the iq2_s super-block-format CONSTANTS as the
// typed integer attrs the verifier pins AND (b) the 1024-entry packed uint64 grid as
// the structural DenseI64ArrayAttr the verifier pins to size 1024.
//
// STRUCTURAL FINDING -- NO NEW ROUTE FAMILY (the bucket verdict, closing the zoo).
// The super-block grid-codebook op takes the EXISTING super-block monolithic route
// family (shared with q4_K / iq4_xs). The grid is an OP attr consumed by the emitter,
// NOT a route-family concern: the emission plan (buildMonolithicBlockDotEmissionPlan)
// and the target export candidate validator both key ONLY off the op name -> route
// family + the kind/scale_model attrs + the ordered ABI roles; neither reads the grid.
// So the shared SuperBlock family + the grid-attr stamping COMPOSE cleanly: one table
// row (SuperBlock, the 4-role ggml vec_dot ABI) + this front door, zero new mechanism.
//
// HONEST FRAMING -- COVERAGE, NOT A NEW FLIP (the iq4_xs framing). iq2_s is NOT in any
// schedule-descriptor autotuner. The grid is an indexed vluxei16 double-gather over the
// 8192-byte packed table + the universal signs256 sign table, both inherently Zvl128b
// legality facts, so the op PINS the m1 integer-core anchor -- m1 is a
// capability-legality fact carried by the op, NOT a gearbox-selected or VLEN-flipped
// shape. So this front door does NOT ride a gearbox: there is no iq2_s schedule
// autotuner. The constructed attr-less op lowers DIRECTLY at the emitter's m1 anchor,
// VLEN-independent (VLEN128 and VLEN256 emit the SAME bytes). The NEW content is the
// auto-CONSTRUCTION feeding the existing iq2_s emitter unchanged.
//
